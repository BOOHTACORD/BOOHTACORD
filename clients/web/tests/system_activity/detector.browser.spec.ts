test('restores a five-minute idle detector without another permission prompt', async ({ page, context }) => {
  const cdp = await context.newCDPSession(page), target = await cdp.send('Target.getTargetInfo')
  await cdp.send('Browser.setPermission', { origin: 'http://127.0.0.1:4967', permission: { name: 'idle-detection' }, setting: 'granted', browserContextId: target.targetInfo.browserContextId })
  await cdp.send('Emulation.setIdleOverride', { isUserActive: false, isScreenUnlocked: true })
  await page.goto('/tests/system_activity/fixture.html')
  await cdp.send('Emulation.setIdleOverride', { isUserActive: false, isScreenUnlocked: true })
  await page.evaluate(() => localStorage.setItem('boohtacord.system-activity.enabled', '1'))
  await page.evaluate(() => (window as any).activityFixture.activity.restore())
  await cdp.send('Emulation.setIdleOverride', { isUserActive: false, isScreenUnlocked: true })
  await expect.poll(() => page.evaluate(() => (window as any).activityFixture.activity.isConfirmedIdle())).toBe(true)
  await expect(page.getByRole('button', { name: /Учитывать активность всего компьютера/ })).toHaveAttribute('aria-pressed', 'true')
  await cdp.send('Emulation.clearIdleOverride')
})

test('settings fit a narrow desktop window', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await page.goto('/tests/system_activity/fixture.html')
  const button = page.getByRole('button', { name: /Учитывать активность всего компьютера/ })
  await button.scrollIntoViewIfNeeded()
  const rect = await button.boundingBox()
  expect(rect).not.toBeNull()
  expect(rect!.x).toBeGreaterThanOrEqual(0)
  expect(rect!.x + rect!.width).toBeLessThanOrEqual(393)
})
