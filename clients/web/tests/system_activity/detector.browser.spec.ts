import { expect, test } from '@playwright/test'

test('permission, active/locked transitions and disable use real Chrome IdleDetector', async ({ page, context }, info) => {
  const cdp = await context.newCDPSession(page)
  const target = await cdp.send('Target.getTargetInfo')
  await cdp.send('Browser.setPermission', { origin: 'http://127.0.0.1:4967', permission: { name: 'idle-detection' }, setting: 'granted', browserContextId: target.targetInfo.browserContextId })
  await cdp.send('Emulation.setIdleOverride', { isUserActive: true, isScreenUnlocked: true })
  await page.goto('/tests/system_activity/fixture.html')
  const button = page.getByRole('button', { name: /Учитывать активность всего компьютера/ })
  await expect(button).toHaveAttribute('aria-pressed', 'false')
  const fitsPanel = await button.evaluate(el => {
    const buttonBox = el.getBoundingClientRect(), panel = el.closest('.profile-panel')!.getBoundingClientRect()
    return buttonBox.bottom <= panel.bottom && buttonBox.right <= panel.right
  })
  expect(fitsPanel).toBe(true)
  await button.click(); await expect(button).toHaveAttribute('aria-pressed', 'true')
  await cdp.send('Emulation.setIdleOverride', { isUserActive: true, isScreenUnlocked: true })
  const reports = () => page.evaluate(() => (window as any).activityFixture.observed.reports as number)
  await expect.poll(reports).toBeGreaterThan(0)
  await page.screenshot({ path: info.outputPath('settings-enabled.png') })
  const before = await reports()
  await cdp.send('Emulation.setIdleOverride', { isUserActive: false, isScreenUnlocked: false })
  await expect.poll(() => page.evaluate(() => (window as any).activityFixture.activity.isConfirmedIdle())).toBe(true)
  expect(await reports()).toBe(before)
  await cdp.send('Emulation.setIdleOverride', { isUserActive: true, isScreenUnlocked: true })
  await expect.poll(() => page.evaluate(() => (window as any).activityFixture.activity.isConfirmedIdle())).toBe(false)
  await expect.poll(reports).toBeGreaterThan(before)
  await button.click(); await expect(button).toHaveAttribute('aria-pressed', 'false')
  await cdp.send('Emulation.clearIdleOverride')
})

