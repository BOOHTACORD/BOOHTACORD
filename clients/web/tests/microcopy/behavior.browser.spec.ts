test('share target and audio capability warnings survive; Escape cancels and removes hints', async ({ page }, info) => {
  await page.goto('/tests/microcopy/fixture.html?surface=share')
  await expect(page.locator('.screen-share-setup__title p')).toHaveCount(0)
  await expect(page.locator('.screen-share-quality__disclaimer')).toContainText('фактическое качество зависит')
  await expect(page.getByText(/не гарантированный сетевой расход/)).not.toBeVisible()
  await expect(page.locator('.screen-share-setup__notice')).toContainText('в окне браузера')
  const details = page.locator('.screen-share-capabilities__details summary')
  await details.focus(); await details.press('Enter')
  await expect(page.getByText(/не гарантированный сетевой расход/)).toBeVisible()
  await expect(page.locator('.screen-share-capabilities__note').filter({ hasText: 'Игровой звук не гарантируется' })).toBeVisible()
  await expect(page.locator('.screen-share-capabilities__note').filter({ hasText: 'Игровой звук не гарантируется' })).toContainText('Игровой звук не гарантируется')
  const close = page.getByRole('button', { name: 'Закрыть', exact: true })
  await close.focus(); await close.press('Tab'); await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('tooltip')).toHaveText('Закрыть')
  await expect(page.getByRole('dialog').getByRole('tooltip')).toBeVisible()
  const hintBox = await page.getByRole('tooltip').boundingBox()
  const dialogBox = await page.getByRole('dialog').boundingBox()
  expect(hintBox!.x).toBeGreaterThanOrEqual(dialogBox!.x + 7)
  expect(hintBox!.x + hintBox!.width).toBeLessThanOrEqual(dialogBox!.x + dialogBox!.width - 7)
  await page.getByRole('tooltip').hover()
  await expect(page.getByRole('tooltip')).toBeVisible()
  expect(await page.getByRole('tooltip').evaluate(element => {
    const box = element.getBoundingClientRect(), hit = document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)
    return hit === element || element.contains(hit)
  })).toBe(true)
  await page.screenshot({ path: info.outputPath('dialog-action-hint.png') })
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.getByTestId('result')).not.toHaveText('start')
})

test('guild disclosure does not submit; errors and unsaved values remain explicit', async ({ page }) => {
  await page.goto('/tests/microcopy/fixture.html?surface=admin&section=guild')
  const field = page.getByLabel('Название гильдии', { exact: true })
  await expect(field).toBeEnabled()
  let patches = 0
  await page.route('**/api/v1/admin/guild-settings', route => {
    if (route.request().method() === 'PATCH') patches++
    return route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE' } } })
  })
  const help = page.getByText('О названии гильдии', { exact: true })
  await help.focus(); await help.press('Enter')
  await expect(page.getByText('Название отображается участникам и на экране входа.', { exact: true })).toBeVisible()
  expect(patches).toBe(0)
  await field.fill('Несохранённая гильдия')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).press('Enter')
  await expect(page.locator('.guild-settings').getByRole('alert')).toBeVisible()
  await expect(field).toHaveValue('Несохранённая гильдия')
  expect(patches).toBe(1)
})

