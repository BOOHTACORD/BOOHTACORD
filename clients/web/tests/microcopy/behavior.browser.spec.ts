test('icon hints work on focus and hover, are hoverable and dismiss without losing focus', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/tests/microcopy/fixture.html?surface=chat')
  const button = page.getByRole('button', { name: 'Другие действия', exact: true })
  await button.focus(); await button.press('Tab'); await page.keyboard.press('Shift+Tab')
  const hint = page.getByRole('tooltip')
  await expect(hint).toHaveText('Другие действия')
  const box = await hint.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(8)
  expect(box!.x + box!.width).toBeLessThanOrEqual(382)
  await page.keyboard.press('Escape')
  await expect(hint).toHaveCount(0)
  await expect(button).toBeFocused()
  await button.evaluate(element => (element as HTMLElement).blur()); await button.hover()
  await expect(hint).toBeVisible()
  await hint.hover()
  await expect(hint).toBeVisible()
  await page.screenshot({ path: info.outputPath('compact-action-hint.png') })
  await page.keyboard.press('Escape')
  await expect(hint).toHaveCount(0)
})

