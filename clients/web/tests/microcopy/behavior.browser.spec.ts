  await expect(mic).toHaveAccessibleName('Выключить микрофон')
  await mic.focus(); await mic.press('Tab'); await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('tooltip')).toHaveText('Выключить микрофон')
