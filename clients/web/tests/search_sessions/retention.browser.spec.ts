import {expect,test} from '@playwright/test'
test('SearchPanel retains independent query/scope/filters across close, origin switch and account reset',async({page})=>{
 await page.route('**/api/v1/members?**',r=>r.fulfill({json:{members:[{user_id:'qa-self',login:'qa-self',display_name:'Self',role:'MEMBER',presence:'online'}]}}))
 await page.goto('/tests/search_sessions/fixture.html')
 const panel=page.getByTestId('search-panel'),query=panel.getByRole('searchbox',{name:'Запрос',exact:true}),author=panel.locator('.search-filters select').nth(0),attachment=panel.locator('.search-filters select').nth(1)
 await panel.locator('.search-filter-disclosure > summary').click()
 await query.fill('Draft search B')
 await panel.getByLabel('Область поиска').selectOption('current')
 await author.selectOption('qa-self')
 await attachment.selectOption('without')
 await panel.getByRole('button',{name:'Закрыть поиск',exact:true}).click()
 await page.getByRole('button',{name:'Search C',exact:true}).click()
 await expect(query).toHaveValue('')
 await expect(author).toHaveValue('')
 await expect(attachment).toHaveValue('any')
 await query.fill('Draft search C')
 await panel.getByRole('button',{name:'Закрыть поиск',exact:true}).click()
 await page.getByRole('button',{name:'Search B',exact:true}).click()
 await expect(query).toHaveValue('Draft search B')
 await expect(panel.getByLabel('Область поиска')).toHaveValue('current')
 await expect(author).toHaveValue('qa-self')
 await expect(attachment).toHaveValue('without')
 await page.getByRole('button',{name:'Search C',exact:true}).click()
 await expect(query).toHaveValue('Draft search C')
 await page.getByRole('button',{name:'End account',exact:true}).click()
 await page.getByRole('button',{name:'Search B',exact:true}).click()
 await expect(query).toHaveValue('')
 await expect(author).toHaveValue('')
 await expect(attachment).toHaveValue('any')
})

test('reopening a submitted query rechecks server ACL instead of retaining old hits',async({page})=>{
 let reads=0
 await page.route('**/api/v1/members?**',r=>r.fulfill({json:{members:[]}}))
 await page.route('**/api/v1/search/messages?**',r=>{
  reads++
  return reads===1?r.fulfill({json:{messages:[]}}):r.fulfill({status:403,json:{error:{code:'FORBIDDEN',message:'Access denied'}}})
 })
 await page.goto('/tests/search_sessions/fixture.html')
 const panel=page.getByTestId('search-panel'),query=panel.getByRole('searchbox',{name:'Запрос',exact:true})
 await query.fill('Submitted B')
 await panel.getByLabel('Область поиска').selectOption('current')
 await panel.getByRole('button',{name:'Найти',exact:true}).click()
 await expect.poll(()=>reads).toBe(1)
 await expect(panel.getByRole('status')).toHaveText('Совпадений нет.')
 await panel.getByRole('button',{name:'Закрыть поиск',exact:true}).click()
 await page.getByRole('button',{name:'Search B',exact:true}).click()
 await expect(query).toHaveValue('Submitted B')
 await expect.poll(()=>reads).toBe(2)
 await expect(panel.getByRole('alert')).toHaveText('Запрос сообщения отклонён: FORBIDDEN.')
 await expect(panel.locator('.search-result')).toHaveCount(0)
})

test('reopening preserves an unsubmitted edit while rechecking the last submitted search',async({page})=>{
 const reads:string[]=[]
 await page.route('**/api/v1/members?**',r=>r.fulfill({json:{members:[]}}))
 await page.route('**/api/v1/search/messages?**',r=>{reads.push(new URL(r.request().url()).searchParams.get('query')??'');return r.fulfill({json:{messages:[]}})})
 await page.goto('/tests/search_sessions/fixture.html')
 const panel=page.getByTestId('search-panel'),query=panel.getByRole('searchbox',{name:'Запрос',exact:true})
 await query.fill('Submitted A')
 await panel.getByRole('button',{name:'Найти',exact:true}).click()
 await expect.poll(()=>reads.length).toBe(1)
 await expect(panel.getByRole('status')).toHaveText('Совпадений нет.')
 await query.fill('Unsubmitted B')
 await panel.getByRole('button',{name:'Закрыть поиск',exact:true}).click()
 await page.getByRole('button',{name:'Search B',exact:true}).click()
 await expect(query).toHaveValue('Unsubmitted B')
 await expect.poll(()=>reads.length).toBe(2)
 expect(reads).toEqual(['Submitted A','Submitted A'])
})

test('reopening restores the actual search result scroll owner after fresh results',async({page})=>{
 const account='11111111-1111-4111-8111-111111111111',conversation='22222222-2222-4222-8222-222222222222'
 let reads=0
 await page.route('**/api/v1/members?**',r=>r.fulfill({json:{members:[{user_id:account,login:'qa-self',display_name:'Self',role:'MEMBER',presence:'online'}]}}))
 await page.route('**/api/v1/members/*',r=>r.fulfill({json:{user_id:account,login:'qa-self',display_name:'Self',role:'MEMBER',presence:'online'}}))
 await page.route('**/api/v1/search/messages?**',r=>{reads++;return r.fulfill({json:{messages:Array.from({length:30},(_,i)=>({id:`00000000-0000-4000-8000-${String(i).padStart(12,'0')}`,kind:'DIRECT_MESSAGE',direct_message_id:conversation,author_id:account,body:'Synthetic scroll result',created_at:'2026-10-12T10:00:00Z',revision:1}))}})})
 await page.goto('/tests/search_sessions/fixture.html')
 const panel=page.getByTestId('search-panel'),host=page.locator('#search-mode-content')
 await panel.getByRole('searchbox',{name:'Запрос',exact:true}).fill('Synthetic scroll')
 await panel.getByRole('button',{name:'Найти',exact:true}).click()
 await expect(panel.locator('.search-result')).toHaveCount(30)
 await host.evaluate(e=>{e.scrollTop=280;e.dispatchEvent(new Event('scroll'))})
 await expect.poll(()=>host.evaluate(e=>e.scrollTop)).toBe(280)
 await page.getByRole('button',{name:'Hide search',exact:true}).click()
 await page.getByRole('button',{name:'Search B',exact:true}).click()
 await expect.poll(()=>reads).toBe(2)
 await expect(panel.locator('.search-result')).toHaveCount(30)
 await expect.poll(()=>host.evaluate(e=>e.scrollTop)).toBe(280)
})
